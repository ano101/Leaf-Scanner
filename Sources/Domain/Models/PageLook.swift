/// Как выглядит страница — один словарь на всё приложение.
///
/// Раньше их было два: «вид» на странице и «цвет» при отправке. Человек
/// видел два списка об одном и том же и не понимал, чем «Чище» отличается
/// от «Цветной». Разделение было техническим, а не смысловым.
///
/// Порядок значений — от тяжёлого к лёгкому: следующий всегда весит меньше
/// предыдущего, и на этом держится предложение «сделать легче», когда файл
/// не влезает в заданный предел.
public enum PageLook: String, Sendable, Codable, CaseIterable {
    /// Без обработки: фотографии, цветные схемы, всё, что не бумага.
    case asShot
    /// Выровненное освещение, белая бумага. Цвет печати и подписи сохранён —
    /// именно этим оригинал отличается от копии.
    case color
    case gray
    /// То, что человек и называет «как из сканера». Самый лёгкий файл.
    case blackAndWhite

    public var titleKey: String { "look.\(rawValue)" }

    /// Следующий вид, который весит меньше.
    public var lighter: PageLook? {
        switch self {
        case .asShot: .color
        case .color: .gray
        case .gray: .blackAndWhite
        case .blackAndWhite: nil
        }
    }

    /// Нужно ли выравнивать освещение. Для снимка, который человек оставил
    /// фотографией, — нет: он снимал не бумагу.
    public var flattensLighting: Bool { self != .asShot }
}
